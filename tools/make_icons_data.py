#!/usr/bin/env python3
"""Encode the hammer icons (from draw_hammers.py) as URE frame data and write src/icons_data.h,
which the mod DLL embeds and appends to the player's MenuIcon8_2.URE at startup.

    py -3 make_icons_data.py OUT.h
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import draw_hammers  # noqa: E402
import ure  # noqa: E402


def c_array(name, data):
    lines = ["static const unsigned char %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 20]) + ",")
    lines.append("};")
    return "\n".join(lines)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    art = draw_hammers.icons()
    parts = ["// Generated by tools/make_icons_data.py - the Build hammer icons as URE frame data",
             "// (52x43, version 2 encoding: RGB555 for block 1, RGB565 for block 2). Our own art.",
             "#pragma once"]
    for key, name in (("hammer_human", "ICON_HUMAN"), ("hammer_devil", "ICON_DEVIL")):
        rows = art[key]
        for rgb565, suffix in ((False, "555"), (True, "565")):
            data = ure.encode_frame(rows, rgb565)
            decoded, _ = ure.decode_frame(data, 52, 43, rgb565)  # round-trip check
            if len(decoded) != 43:
                raise SystemExit("encoding check failed")
            parts.append(c_array("%s_%s" % (name, suffix), data))
    open(sys.argv[1], "w", newline="\n").write("\n\n".join(parts) + "\n")
    print("wrote", sys.argv[1])
